const assert = require('node:assert/strict')
const { writeFileSync } = require('node:fs')
const { join } = require('node:path')
const { setTimeout: delay } = require('node:timers/promises')
const { app, BrowserWindow } = require('electron')
const origin = process.argv[2]
assert.equal(new URL(origin).hostname, 'agent-phase4.localhost')
app.setPath('userData', process.argv[3])
app.commandLine.appendSwitch('disable-gpu')
async function main() {
  await app.whenReady()
  const win = new BrowserWindow({ show: false, width: 1180, height: 900, webPreferences: { backgroundThrottling: false } })
  win.webContents.session.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (r, done) => done({ cancel: new URL(r.url).origin !== origin }))
  const run = (fn, ...args) => win.webContents.executeJavaScript('(' + fn.toString() + ')(...' + JSON.stringify(args) + ')')
  const wait = async (fn, ...args) => {
    const until = Date.now() + 9000
    do { if (await run(fn, ...args)) return; await delay(35) } while (Date.now() < until)
    throw new Error('SP_UI_WAIT: ' + fn.toString())
  }
  const bindCard = async () => {
    await wait(() => [...document.querySelectorAll('.trk-title')].some(el => el.textContent === '偶像大师'))
    await run(() => { window.spCard = () => [...document.querySelectorAll('.trk-row')].find(el => el.querySelector('.trk-title')?.textContent === '偶像大师') })
  }
  const shot = async (selector, name) => {
    if (!process.env.TRACK_SPECIALS_SHOTS) return
    const bounds = await run(async selector => {
      const el = selector ? document.querySelector(selector) : window.spCard().querySelector('.trk-body')
      el.scrollIntoView({ block: 'center', behavior: 'instant' })
      const shade = el.closest('.dlg-backdrop')
      if (shade) await Promise.all(shade.getAnimations({ subtree: true }).filter(a => a.effect.getComputedTiming().endTime < 1000).map(a => a.finished.catch(() => {})))
      await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
      const b = el.getBoundingClientRect()
      return { x: Math.max(0, Math.floor(b.x)), y: Math.max(0, Math.floor(b.y)), width: Math.ceil(b.width), height: Math.ceil(b.height) }
    }, selector)
    await delay(140)
    writeFileSync(join(process.env.TRACK_SPECIALS_SHOTS, name), (await win.webContents.capturePage(bounds)).toPNG())
  }
  await win.loadURL(origin + '/__agent-test/login/alice')
  await bindCard()
  await wait(() => !document.querySelector('.sp'))
  const state = () => run(() => {
    const card = window.spCard()
    return [card.querySelector('.trk-ep').textContent, card.querySelector('.ep-num').textContent, card.querySelector('.ep-plus').disabled, card.querySelector('.trk-chapters').textContent]
  })
  assert.deepEqual(await state(), ['25 / 26','EP 25',false,'正篇 25 集 · SP 26'])
  assert.match(await run(() => window.spCard().querySelector('.ep-plus').title), /SP 26.*名为765的故事/)
  await shot('', 'card-at-25.png')
  await run(() => window.spCard().querySelector('.ep-plus').click())
  await wait(() => window.spCard().querySelector('.ep-num').textContent === 'SP 26')
  assert.deepEqual(await state(), ['26 / 26','SP 26',true,'正篇 25 集 · SP 26'])
  await run(() => window.spCard().querySelector('.ep-minus').click())
  await wait(() => window.spCard().querySelector('.ep-num').textContent === 'EP 25')
  await run(() => window.spCard().querySelector('[role="slider"]').dispatchEvent(new KeyboardEvent('keydown', { key: 'End', bubbles: true })))
  await wait(() => window.spCard().querySelector('[role="slider"]').getAttribute('aria-valuetext') === 'SP 26，共 26 集')
  await run(() => window.spCard().querySelector('button[title^="挑个源"]').click())
  await wait(() => /SP 26/.test(document.querySelector('.dlg-wsrc h3')?.textContent ?? ''))
  await run(() => document.querySelector('.dlg-wsrc .dlg-close').click())
  win.setContentSize(390, 844)
  await run(() => window.spCard().querySelector('.trk-edit-mobile').click())
  await wait(() => document.querySelector('.dlg .ep-ctrl:not(.season-ctrl) .ep-num')?.textContent === 'SP 26')
  await run(() => document.querySelector('.dlg-close').click())
  await shot('', 'card-at-sp.png')
  await run(() => window.spCard().querySelector('button[title$="集好看"]').click())
  await wait(() => document.querySelectorAll('.ge-ep').length === 26)
  assert.deepEqual(await run(() => [...document.querySelectorAll('.ge-chapter-heading')].map(x => x.textContent)), ['正篇','SP 特别篇'])
  assert.equal(await run(() => document.querySelector('.ge-specials button').textContent), 'SP 26名为765的故事')
  await run(() => document.querySelector('.ge-specials button').click())
  await wait(() => !!document.querySelector('.ge-specials .on'))
  await shot('.ge-dlg', 'episode-groups.png')
  await run(() => document.querySelectorAll('.ge-view-btn')[1].click())
  assert.deepEqual(await run(() => [...document.querySelectorAll('.ge-row-ep')].map(x => x.textContent)), ['25','SP 26'])
  await run(() => document.querySelector('.ge-dlg .dlg-close').click())
  await run(() => [...document.querySelectorAll('.view-mode button')].find(x => x.textContent === '列表').click())
  await wait(() => [...document.querySelectorAll('.trk-list-row')].some(el => el.textContent.includes('偶像大师') && el.textContent.includes('SP 26 / 26') && el.textContent.includes('正篇 25 集 · SP 26')))
  await wait(async () => (await (await fetch('/api/tracks/11577/good-episodes')).json()).goodEpisodes.includes(26))
  await win.reload()
  await wait(() => [...document.querySelectorAll('.trk-list-row,.trk-row')].some(el => el.textContent.includes('偶像大师') && el.textContent.includes('SP 26')))
  console.log('PASS 浏览器：EP 25 → SP 26 → EP 25，末集封顶，键盘、选源、手机详情、分组标记、列表与刷新')
  await run(() => [...document.querySelectorAll('.view-mode button')].find(x => x.textContent === '卡片').click())
  await wait(() => [...document.querySelectorAll('.trk-title')].some(el => el.textContent === '新加入样本'))
  await run(() => {
    window.resetCard = () => [...document.querySelectorAll('.trk-row')].find(el => el.querySelector('.trk-title')?.textContent === '新加入样本')
    window.resetCard().querySelector('.ep-num').click()
  })
  await run(() => {
    const input = window.resetCard().querySelector('.ep-num-input')
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, '3')
    input.dispatchEvent(new Event('input', { bubbles: true }))
  })
  await run(() => window.resetCard().querySelector('.ep-num-input').dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })))
  await wait(() => window.resetCard().querySelector('.ep-num').textContent === 'SP 1')
  await run(() => window.resetCard().querySelector('button[title="标记鉴赏神回"]').click())
  await wait(() => document.querySelectorAll('.ge-specials .ge-ep').length === 2)
  await run(() => document.querySelector('.ge-specials .ge-ep').click())
  await wait(async () => (await (await fetch('/api/tracks/304/good-episodes')).json()).goodEpisodes.includes(3))
  assert.equal(await run(() => document.querySelector('.ge-grid .ge-ep').getAttribute('aria-pressed')), 'false')
  console.log('PASS 直接输第 3 格显示 SP 1；点亮 SP 1 写回第 3 格，正篇第 1 集仍未标记')
  win.destroy()
}
main().then(() => app.quit(), error => { console.error(error); app.exit(1) })
