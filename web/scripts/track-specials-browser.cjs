const assert = require('node:assert/strict')
const { writeFileSync } = require('node:fs')
const { join } = require('node:path')
const { setTimeout: delay } = require('node:timers/promises')
const { app, BrowserWindow } = require('electron')
const origin = process.argv[2]
assert.equal(new URL(origin).hostname, 'agent-phase4.localhost')
app.setPath('userData', process.argv[3])
app.commandLine.appendSwitch('disable-gpu')
async function main() {
  await app.whenReady()
  const win = new BrowserWindow({ show: false, width: 1180, height: 900, webPreferences: { backgroundThrottling: false } })
  const chapterReads = []
  win.webContents.session.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (r, done) => {
    const url = new URL(r.url)
    if (url.pathname.endsWith('/chapters')) chapterReads.push(url.pathname)
    done({ cancel: url.origin !== origin })
  })
  const run = (fn, ...args) => win.webContents.executeJavaScript('(' + fn.toString() + ')(...' + JSON.stringify(args) + ')')
  const wait = async (fn, ...args) => {
    const until = Date.now() + 9000
    do { if (await run(fn, ...args)) return; await delay(35) } while (Date.now() < until)
    throw new Error('SP_UI_WAIT: ' + fn.toString())
  }
  const bindCard = async () => {
    await wait(() => [...document.querySelectorAll('.trk-title')].some(el => el.textContent === '偶像大师'))
    await run(() => { window.card = title => [...document.querySelectorAll('.trk-row')].find(el => el.querySelector('.trk-title')?.textContent === title); window.spCard = () => window.card('偶像大师') })
  }
  const shot = async (selector, name) => {
    if (!process.env.TRACK_SPECIALS_SHOTS) return
    const bounds = await run(async selector => {
      const el = selector ? document.querySelector(selector) : window.spCard().querySelector('.trk-body')
      if (!selector) el.scrollIntoView({ block: 'center', behavior: 'instant' })
      const shade = el.closest('.dlg-backdrop')
      if (shade) await Promise.all(shade.getAnimations({ subtree: true }).filter(a => a.effect.getComputedTiming().endTime < 1000).map(a => a.finished.catch(() => {})))
      await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
      const b = el.getBoundingClientRect()
      return { x: Math.max(0, Math.floor(b.x)), y: Math.max(0, Math.floor(b.y)), width: Math.ceil(b.width), height: Math.ceil(b.height) }
    }, selector)
    await delay(140)
    writeFileSync(join(process.env.TRACK_SPECIALS_SHOTS, name), (await win.webContents.capturePage(bounds)).toPNG())
  }
  await win.loadURL(origin + '/__agent-test/login/alice')
  await bindCard()
  await wait(() => !document.querySelector('.sp'))
  const go = title => run(title => window.card(title).querySelector('button[title="标记鉴赏神回"],button[title$="集好看"]').click(), title)
  const close = () => run(() => document.querySelector('.ge-dlg .dlg-close').click())
  const point = (selector) => run(s => {
    const b = document.querySelector(s).getBoundingClientRect()
    return { x: Math.round(b.left + b.width/2), y: Math.round(b.top + b.height/2) }
  }, selector)
  const hover = async selector => win.webContents.sendInputEvent({ type: 'mouseMove', ...await point(selector) })
  const tip = () => run(() => document.querySelector('[role="tooltip"]')?.textContent)
  const position = n => `[data-position="${n}"]`
  const cardState = title => run(title => {
    const c = window.card(title)
    return [c.querySelector('.trk-ep').textContent, c.querySelector('.ep-num')?.textContent, c.querySelector('.ep-plus')?.disabled]
  }, title)
  assert.equal(chapterReads.length, 0)
  assert.deepEqual(await cardState('偶像大师'), ['25 / 25','EP 25',true])
  assert.deepEqual(await cardState('偶像大师 XENOGLOSSIA'), ['26 / 26','EP 26',true])
  assert.deepEqual(await cardState('SP 从 1 重新编号'), ['2 / 4','EP 2',false])
  assert.deepEqual((await cardState('只收录特别篇')).slice(0, 1), ['无正篇'])
  assert.equal(await run(() => !!document.querySelector('.trk-chapters')), false)
  await shot('', 'card-main.png')
  await run(() => window.spCard().querySelector('[role="slider"]').dispatchEvent(new KeyboardEvent('keydown', { key: 'End', bubbles: true })))
  await run(() => window.spCard().querySelector('.ep-num').click())
  await run(() => window.spCard().querySelector('input.ep-num').dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true })))
  await run(() => window.spCard().querySelector('button[title^="挑个源"]').click())
  await wait(() => /第 25 话/.test(document.querySelector('.dlg-wsrc h3')?.textContent ?? ''))
  await run(() => document.querySelector('.dlg-wsrc .dlg-close').click())

  await go('偶像大师 XENOGLOSSIA')
  await wait(() => document.querySelectorAll('.ge-ep').length === 34)
  await delay(350)
  const geometry = () => run(() => [...document.querySelectorAll('.ge-ep')].map(b => [b.offsetLeft,b.offsetTop,b.offsetWidth,b.offsetHeight]))
  const before = await geometry()
  await hover(position(9))
  await wait(() => document.querySelector('.ge-tip')?.textContent.includes('23:40'))
  assert.match(await tip(), /EP 9鍵盤中文标题键盘首播2007-05-28时长23:40/)
  assert.deepEqual(await geometry(), before)
  await shot('.ge-dlg', 'xeno-ep09.png')
  await hover('.ge-tip')
  await delay(160)
  assert.match(await tip(), /键盘/)
  await run(() => window.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true })))
  await wait(() => !!document.querySelector('.ge-dlg') && !document.querySelector('.ge-tip'))
  await hover(position(2))
  await wait(() => document.querySelector('.ge-tip')?.textContent.includes('暂无章节资料'))
  const keyboard = win.webContents.debugger
  keyboard.attach('1.3')
  await keyboard.sendCommand('Emulation.setFocusEmulationEnabled', { enabled: true })
  await run(() => document.querySelector('[data-position="8"]').focus())
  for (const type of ['rawKeyDown','keyUp']) await keyboard.sendCommand('Input.dispatchKeyEvent', { type, key:'Tab', code:'Tab', windowsVirtualKeyCode:9 })
  try {
    await wait(() => document.activeElement?.getAttribute('aria-label') === 'EP 9' && document.querySelector('.ge-tip')?.textContent.includes('键盘'))
  } catch (error) {
    throw new Error('键盘焦点实测：' + JSON.stringify(await run(() => [document.hasFocus(),document.activeElement?.outerHTML.slice(0,300),document.querySelector('.ge-tip')?.textContent])), {cause:error})
  }
  keyboard.detach()
  assert.deepEqual(chapterReads, ['/api/tracks/3271/chapters'])
  await close()

  await go('偶像大师')
  await wait(() => document.querySelectorAll('.ge-ep').length === 26)
  assert.deepEqual(await run(() => [...document.querySelectorAll('.ge-ep')].slice(-2).map(b => [b.textContent,b.getAttribute('aria-label')])), [['25','EP 25'],['26','SP 26']])
  assert.deepEqual(await run(() => [...document.querySelectorAll('.ge-sp-label')].map(b=>b.textContent)), ['SP'])
  await delay(350)
  const last = await run(() => [document.querySelector('.ge-ep[data-position="25"]'), document.querySelector('.ge-sp-start'), document.querySelector('.ge-sp-start .ge-ep')].map(e => [e.getBoundingClientRect().top, e.getBoundingClientRect().height]))
  assert(last.every(b => Math.abs(b[0]-last[0][0]) < 1 && Math.abs(b[1]-last[0][1]) < 1), 'SP 与末集同排且等高：' + JSON.stringify(last))
  await shot('.ge-dlg', 'idol-grid.png')
  await hover(position(26))
  await wait(() => document.querySelector('.ge-tip')?.textContent.includes('名为765的故事'))
  assert.match(await tip(), /SP 26765プロという物語中文标题名为765的故事首播2012-06-16时长25:29/)
  await shot('.ge-dlg', 'idol-sp26.png')
  await run(() => document.querySelector('.ge-sp-start button').click())
  await wait(() => !!document.querySelector('.ge-sp-start .on'))
  await run(() => document.querySelectorAll('.ge-view-btn')[1].click())
  assert.deepEqual(await run(() => [...document.querySelectorAll('.ge-row-ep')].map(x => x.textContent)), ['25','SP 26'])
  assert.equal(await tip(), undefined)
  await close()

  win.setContentSize(390, 844)
  await run(() => window.spCard().querySelector('.trk-edit-mobile').click())
  await wait(() => document.querySelector('.dlg .ep-ctrl:not(.season-ctrl) .ep-num')?.textContent === 'EP 25')
  await run(() => document.querySelector('.dlg-close').click())
  await go('新加入样本')
  await wait(() => document.querySelectorAll('.ge-ep').length === 4)
  await delay(380)
  assert.deepEqual(await run(() => [...document.querySelectorAll('.ge-ep')].map(b => b.textContent)), ['01','02','01','2.5'])
  const debug = win.webContents.debugger
  debug.attach('1.3')
  await debug.sendCommand('Emulation.setTouchEmulationEnabled', { enabled: true })
  const tap = async (selector, hold) => {
    const pt = await point(selector)
    await debug.sendCommand('Input.dispatchTouchEvent', {type:'touchStart',touchPoints:[pt]})
    await delay(hold)
    await debug.sendCommand('Input.dispatchTouchEvent', {type:'touchEnd',touchPoints:[]})
  }
  await tap(position(3), 580)
  await wait(() => document.querySelector('.ge-tip')?.textContent.startsWith('SP 1'))
  assert.equal(await run(() => document.querySelector('.ge-sp-start button').getAttribute('aria-pressed')), 'false')
  assert(await run(() => { const b=document.querySelector('.ge-tip').getBoundingClientRect(); return b.left>=0 && b.right<=innerWidth && b.bottom<=innerHeight }))
  await tap(position(3), 40)
  await wait(() => !!document.querySelector('.ge-sp-start .on'))
  assert.equal(await run(() => document.querySelector('.ge-ep').getAttribute('aria-pressed')), 'false')
  await debug.sendCommand('Emulation.setTouchEmulationEnabled', { enabled: false })
  debug.detach()
  await close()
  await run(() => [...document.querySelectorAll('.view-mode button')].find(x => x.textContent === '列表').click())
  await wait(() => [...document.querySelectorAll('.trk-list-row')].some(el => el.textContent.includes('偶像大师') && el.textContent.includes('EP 25 / 25')))
  await wait(async () => (await (await fetch('/api/tracks/11577/good-episodes')).json()).goodEpisodes.includes(26))
  await win.reload()
  await wait(() => [...document.querySelectorAll('.trk-list-row,.trk-row')].some(el => el.textContent.includes('偶像大师') && el.textContent.includes('25 / 25')))
  console.log('PASS 两例卡片只计正篇；SP 仅在神回网格内联；按键、刷新、手机详情、手填上限不变')
  console.log('PASS EP 9 与 SP 26 展示双语标题/首播/时长；空章节不假填；悬停不挤位、不再读接口')
  console.log('PASS 手机长按查看不点亮，轻点 SP 1 只标第三格，不碰正篇 1')
  win.destroy()
}
main().then(() => app.quit(), error => { console.error(error); app.exit(1) })
