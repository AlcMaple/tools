const assert=require('node:assert/strict')
const {setTimeout:delay}=require('node:timers/promises')
const {app,BrowserWindow}=require('electron')
const origin=process.argv[2]
assert(origin&&new URL(origin).hostname==='agent-phase4.localhost')
app.setPath('userData',process.argv[3]);app.commandLine.appendSwitch('disable-gpu');app.on('window-all-closed',()=>{})
async function main(){
 await app.whenReady()
 const win=new BrowserWindow({show:false,width:1280,height:900,webPreferences:{contextIsolation:true,nodeIntegration:false}})
 win.webContents.session.webRequest.onBeforeRequest({urls:['http://*/*','https://*/*']},(r,done)=>done({cancel:new URL(r.url).origin!==origin}))
 const read=x=>win.webContents.executeJavaScript(x)
 const wait=async x=>{const end=Date.now()+10000;while(Date.now()<end){if(await read(x))return;await delay(25)}throw Error('TAG_WAIT_TIMEOUT: '+x)}
 const card=title=>`Array.from(document.querySelectorAll('article')).find(x=>x.textContent.includes(${JSON.stringify(title)}))`
 const click=x=>read(`(()=>{const el=${x};if(!el)throw Error('TAG_TARGET_MISSING');el.click()})()`)
 const fill=v=>read(`(()=>{const e=document.querySelector('.tagx-input');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(v)});e.dispatchEvent(new Event('input',{bubbles:true}))})()`)
 const key=(k,composing=false)=>read(`document.querySelector('.tagx-input').dispatchEvent(new KeyboardEvent('keydown',{key:${JSON.stringify(k)},bubbles:true,isComposing:${composing}}))`)
 const open=async title=>{await click(card(title)+`.querySelector('.tagx-add')`);await wait("document.querySelector('.tagx-input')")}
 await win.loadURL(origin+'/__agent-test/login/alice')
 await wait("document.querySelectorAll('article').length===4")
 await open('候补手帐一号')
 assert(await read("Array.from(document.querySelectorAll('[role=option]')).some(x=>x.textContent==='周末再看')"),'EXISTING_TAG_CHOICES_MUST_BE_VISIBLE')
 assert(!(await read("document.querySelector('[role=listbox]').textContent")).includes('公共题材'),'BGM_TAG_MUST_NOT_ENTER_OWN_TAG_CHOICES')
 assert(!(await read("document.querySelector('[role=listbox]').textContent")).includes('另一个账号'),'OWNER_TAGS_MUST_STAY_ISOLATED')
 await fill('周');await wait("document.querySelectorAll('[role=option]').length===1")
 assert.equal(await read("document.querySelector('[role=option]').dispatchEvent(new MouseEvent('mousedown',{bubbles:true,cancelable:true}))"),false,'CHOICE_MUST_PREVENT_PREMATURE_BLUR')
 await click("document.querySelector('[role=option]')")
 await wait(card('候补手帐一号')+`.querySelector('button[aria-label="删除标签 周末再看"]')`)
 await open('候补手帐一号')
 assert(!(await read("document.querySelector('[role=listbox]').textContent")).includes('周末再看'),'DUPLICATE_CHOICE_MUST_BE_EXCLUDED')
 await fill('取消的草稿');await key('Escape');await wait("!document.querySelector('.tagx-input')")
 assert(!(await read(card('候补手帐一号')+'.textContent')).includes('取消的草稿'))
 await open('候补手帐一号');await fill('新计划');await key('Enter',true)
 assert(await read("!!document.querySelector('.tagx-input')"),'IME_ENTER_MUST_NOT_COMMIT')
 await key('Enter');await wait(card('候补手帐一号')+`.querySelector('button[aria-label="删除标签 新计划"]')`)
 console.log('PASS candidate reuse, filtering, no BGM/other-owner tags, duplicate exclusion, Escape and IME')
 await open('候补手帐二号');await key('ArrowDown')
 assert.equal(await read("document.querySelector('[role=option][aria-selected=true]').textContent"),'周末再看')
 await read("fetch('/api/tracks/-14',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({userTags:['接着看']})}).then(r=>{if(!r.ok)throw Error('FIXTURE_WRITE_FAILED')})")
 await read("window.dispatchEvent(new StorageEvent('storage',{key:'mt_cache:tracks:ui_alice',newValue:'{\"data\":[]}'}))")
 await wait("document.querySelector('[role=option]')?.textContent!=='周末再看'")
 assert.equal(await read("document.querySelector('[role=option][aria-selected=true]')?.textContent"),'周末再看','RERANK_MUST_KEEP_SELECTED_TAG')
 await key('Enter');await wait(card('候补手帐二号')+`.querySelector('button[aria-label="删除标签 周末再看"]')`)
 await read("fetch('/api/tracks/-14',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({userTags:['周末再看','接着看']})}).then(r=>{if(!r.ok)throw Error('FIXTURE_RESTORE_FAILED')})")
 await open('候补手帐二号');await fill('接');await key('ArrowDown');await key('Enter')
 await wait(card('候补手帐二号')+`.querySelector('button[aria-label="删除标签 接着看"]')`)
 await click(card('候补手帐三号')+`.querySelector('button[aria-label*="封面和标签"]')`)
 await wait("document.querySelector('[role=dialog]')")
 await click("document.querySelector('[role=dialog] .tagx-add')")
 await wait("Array.from(document.querySelectorAll('[role=option]')).some(x=>x.textContent==='周末再看')")
 await click("Array.from(document.querySelectorAll('[role=option]')).find(x=>x.textContent==='周末再看')")
 await wait("document.querySelector('[role=dialog] button[aria-label=\"删除标签 周末再看\"]')")
 await click("document.querySelector('[role=dialog] button[aria-label=\"关闭\"]')")
 await open('候补手帐三号');await fill('失焦保存');await read("document.querySelector('.tagx-input').dispatchEvent(new FocusEvent('focusout',{bubbles:true,relatedTarget:document.querySelector('#trkSearch')}))")
 await wait(card('候补手帐三号')+`.querySelector('button[aria-label="删除标签 失焦保存"]')`)
 await wait("fetch('/api/tracks').then(r=>{if(!r.ok)throw Error('FIXTURE_READ_FAILED');return r.json()}).then(r=>{const t=r.data.find(x=>x.bgmId===-13);return t?.userTags.includes('周末再看')&&t.userTags.includes('失焦保存')})")
 await win.reload();await wait("document.querySelectorAll('article').length===4")
 assert((await read(card('候补手帐三号')+'.textContent')).includes('周末再看'))
 await win.loadURL(origin+'/__agent-test/login/bob');await wait("document.body.textContent.includes('ui_bob')&&document.querySelectorAll('article').length===1")
 await open('另一账号');assert.equal(await read("document.querySelectorAll('[role=option]').length"),0,'PREVIOUS_OWNER_TAGS_MUST_NOT_REMAIN')
 await key('Escape');console.log('PASS keyboard, edit dialog, persistence and account switch')
 console.log('TRACK_TAGS_COMPLETE');win.destroy()
}
main().then(()=>app.exit(0)).catch(e=>{console.error(e);app.exit(1)})
